# 半角标点/排版问题
PUNCT_PATTERNS = [
    (r"[，。！？；：、]{0,1}[A-Za-z0-9]*[,.!?;:](?!\d)", "半角标点"),
    (r"[ ]{2,}", "连续空格"),
    (r"\n{3,}", "连续空行"),
    (r"[（(](?=[^()（）]{1,20}[)）])", "半角括号提示"),
]

# 专名一致性: 均应为合法写法; 出现"其他写法"时报
NAMES = ["秦尘", "九瞳", "归墟", "玄灵", "凝脉", "宗师", "破虚", "洞玄",
         "摄魂", "锁魂", "回照", "定渊", "幽冥殿", "碑林", "万域"]
NAME_TYPOS = {
    "秦尘": ["秦晨", "臣尘", "陈尘"],
    "九瞳": ["九疃", "九曈"],
    "归墟": ["归虚", "归须"],
    "玄灵": ["悬灵"],
    "凝脉": ["疑脉"],
    "破虚": ["破需", "破虑"],
    "幽冥殿": ["幽明殿"],
    "碑林": ["避林"],
}


def ctx(content, pos, width=9):
    s = max(0, pos - width)
    return content[s:pos + width + 2].replace("\n", "⏎")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-ch", type=int, default=51)
    ap.add_argument("--max-ch", type=int, default=200)
    ap.add_argument("--json", default=None)
    args = ap.parse_args()

    conn = pymysql.connect(**DB_CONFIG)
    cur = conn.cursor()
    cur.execute(
        "SELECT chapter_num, title, content FROM novel_chapter "
        "WHERE novel_id=1 AND is_deleted=0 AND chapter_num BETWEEN %s AND %s "
        "ORDER BY chapter_num", (args.min_ch, args.max_ch))
    rows = cur.fetchall()
    cur.close(); conn.close()

    # 清理占位对(错误==正确)
    pairs = [(b, g) for b, g in TYPO_PAIRS if b != g and "占位" not in g and b != "换了 Ortiz"]
    bad = []
    total_hits = 0
    for num, title, content in rows:
        for pat, fix in pairs:
            for m in re.finditer(re.escape(pat), content):
                total_hits += 1
                bad.append({"ch": num, "type": "typo", "pat": pat, "fix": fix,
                            "ctx": ctx(content, m.start())})
        for pat, label in PUNCT_PATTERNS:
            for m in re.finditer(pat, content):
                total_hits += 1
                bad.append({"ch": num, "type": "punct", "pat": label,
                            "fix": "", "ctx": ctx(content, m.start())})
        for name, typos in NAME_TYPOS.items():
            for t in typos:
                for m in re.finditer(re.escape(t), content):
                    total_hits += 1
                    bad.append({"ch": num, "type": "name", "pat": t, "fix": name,
                                "ctx": ctx(content, m.start())})

    # 打印: 按类型/模式聚合
    agg = defaultdict(lambda: {"count": 0, "chapters": set(), "samples": []})
    for b in bad:
        key = (b["type"], b["pat"], b["fix"])
        a = agg[key]
        a["count"] += 1
        a["chapters"].add(b["ch"])
        if len(a["samples"]) < 3:
            a["samples"].append((b["ch"], b["ctx"]))

    print(f"扫描 {len(rows)} 章, 命中 {total_hits} 处, {len(agg)} 种模式\n")
    for (typ, pat, fix), a in sorted(agg.items(), key=lambda x: -x[1]["count"]):
        chs = sorted(a["chapters"])
        rng = f"{chs[0]}-{chs[-1]}" if len(chs) > 1 else str(chs[0])
        print(f"[{typ}] {pat} -> {fix}  ×{a['count']}  章节: {rng}")
        for ch, c in a["samples"]:
            print(f"    第{ch}章 …{c}…")
    if args.json:
        with open(args.json, "w", encoding="utf-8") as f:
            json.dump(bad, f, ensure_ascii=False, indent=1)
        print(f"\n明细已写 {args.json}")


if __name__ == "__main__":
    main()
